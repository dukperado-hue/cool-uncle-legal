CLEAN=[(r'\[\[/?HL\]\]',''),(r'\[\[XREF:[^|\]]*\|([^\]]*)\]\]',r'\1'),(r'\[\[BOX:[^\]]*\]\]',''),(r'\[\[/BOX\]\]',''),(r'\[\[(?:IMG|FIG:[^\]]*|/?Y)\]\]',''),(r'\*\*',''),(r'^\*\s+','• ')]
def clean(s):
    for p,r in CLEAN: s=re.sub(p,r,s)
    return s
def srcnum(s):
    r=re.search(r'ครั้งที่ (\d)',s); return r and r.group(1)
def build():
    have=collections.defaultdict(set)
    for k,v in A.items():
        for n in v.get('lectureNotes',[]):
            if 'เฉลย' not in n['source']: have[srcnum(n['source'])].add(k)
    out=[];skipped=[]
    for n,rngs,arts,topic,slide in M:
        lines=[]
        for s,e in rngs: lines+=L[n][s:e+1]
        txt='\n'.join(clean(x).rstrip() for x in lines).strip()
        txt=re.sub(r'\n{3,}','\n\n',txt)
        for a in arts:
            if a not in A: skipped.append((n,a,'nokey')); continue
            if n!=5 and a in have[str(n)]: skipped.append((n,a,'covered')); continue
            out.append(dict(lecture=n,article=a,topic=topic,text=txt,source=(SRC_SLIDE(n) if slide else SRC(n))))
    return out,skipped
