/*
 * build_data.js — สร้างไฟล์ข้อมูลของ v2 จากข้อมูลเดิมของ "แจ้งก่อนจุด" v1
 * รัน:  node bunkfai/v2/build_data.js
 *
 * แหล่งข้อมูลจริงยังอยู่ที่ bunkfai/ (data.js, amphoes.js, contacts.js, amphoe_contacts.js)
 * ห้ามแก้ไฟล์ใน v2/data/ ด้วยมือ — แก้ที่ต้นทางแล้วรันสคริปต์นี้ใหม่
 * ทุกไฟล์ที่สร้างจะมี meta (วันที่สร้าง + sha256 ของไฟล์ต้นทาง) เพื่อตอบได้ว่า "ข้อมูลนี้ฉบับไหน"
 */
'use strict';
const fs = require('fs'), path = require('path'), vm = require('vm'), crypto = require('crypto');
const SRC = path.resolve(__dirname, '..');
const OUT = path.join(__dirname, 'data');
const AIRSPACE_EFFECTIVE = '2026-07-09'; // ตามที่ระบุใน app.js (AIP Thailand AIRAC)

function read(f) { return fs.readFileSync(path.join(SRC, f), 'utf8'); }
function sha(f) { return crypto.createHash('sha256').update(fs.readFileSync(path.join(SRC, f))).digest('hex').slice(0, 16); }
function run(f, expose) {
  const ctx = { window: {} }; vm.createContext(ctx);
  vm.runInContext(read(f) + '\n;this.__o=' + expose + ';', ctx);
  return ctx.__o;
}
function write(name, key, obj) {
  const txt = '/* AUTO-GENERATED by v2/build_data.js — do not edit by hand */\n' +
    'window.BF_DATA=window.BF_DATA||{};window.BF_DATA.' + key + '=' + JSON.stringify(obj) + ';\n';
  fs.writeFileSync(path.join(OUT, name), txt, 'utf8');
  console.log(name.padEnd(26), (Buffer.byteLength(txt) / 1024).toFixed(1) + ' KB');
}
const builtAt = new Date().toISOString();

// ---- data.js: สนามบิน + ระเบียบรายจังหวัด ----
const d = run('data.js', '{AIRPORTS:AIRPORTS,PROV_REF:PROV_REF,PROV_DATA:PROV_DATA}');

const airports = d.AIRPORTS.map(a => ({
  icao: a.icao, nameTh: a.nameTh, nameEn: a.nameEn, lat: a.lat, lon: a.lon,
  rwy: a.rwy, rwyBearingDeg: a.rwyBearingDeg, provinceTh: a.provinceTh, provinceEn: a.provinceEn,
  phz_bands: (a.zones && a.zones.phz_bands) || []
}));
write('airspace.js', 'airspace', {
  meta: { builtAt, source: 'AIP Thailand', sourceNote: 'ตามที่ระบุในโค้ด v1 (bunkfai/app.js)', effective: AIRSPACE_EFFECTIVE,
          from: [{ file: 'data.js', sha256: sha('data.js') }],
          status: 'reference', note: 'ยังไม่ผ่านการรับรองโดย กพท. — ดู sandbox/AIRPORT-DATA-AUDIT.md' },
  lhzKm: 10, airports
});

// รายการแก้ไขข้อมูลต้นทางที่ตรวจพบ — ทุกรายการต้องมีเหตุผลและถูกบันทึกใน meta.corrections
const CORRECTIONS = [
  { province: 'Buri Ram', field: 'airportNotify', from: 'VTPB', to: 'VTUO',
    why: 'ข้อความต้นทางอ้าง VTPB (เพชรบูรณ์) แต่สนามบินบุรีรัมย์ในรายการสนามบินคือ VTUO' }
];
const applied = [];
const provinces = d.PROV_REF.map(p => {
  const key = p.en === 'Bangkok' ? 'Bangkok Metropolis' : p.en;
  const r0 = d.PROV_DATA[key] || d.PROV_DATA[p.en] || null;
  const r = r0 ? JSON.parse(JSON.stringify(r0)) : null;
  CORRECTIONS.forEach(c => {
    if (r && (c.province === p.en || c.province === key) && typeof r[c.field] === 'string' && r[c.field].includes(c.from)) {
      r[c.field] = r[c.field].split(c.from).join(c.to); applied.push(c);
    }
  });
  return { en: p.en, th: p.th, region: p.region, lat: p.lat, lon: p.lon, reg: r };
});
write('regulations.js', 'regulations', {
  meta: { builtAt, source: 'ประกาศจังหวัด/ระเบียบที่รวบรวมใน v1', note: d.PROV_DATA['#notes'] || '', corrections: applied,
          from: [{ file: 'data.js', sha256: sha('data.js') }] },
  provinces
});

// ---- amphoes / contacts ----
const am = run('amphoes.js', 'window.AMPHOES');
write('amphoes.js', 'amphoes', { meta: { builtAt, source: 'ชุดข้อมูลอำเภอ กรมการปกครอง (DOPA) ผ่าน v1', from: [{ file: 'amphoes.js', sha256: sha('amphoes.js') }] }, byProvinceEn: am });

const ct = run('contacts.js', 'window.CONTACTS');
write('contacts.js', 'contacts', { meta: { builtAt, source: 'aerothai.co.th, AIP Thailand GEN 3.3 ผ่าน v1', from: [{ file: 'contacts.js', sha256: sha('contacts.js') }] }, ...ct });

const ac = run('amphoe_contacts.js', 'window.AMPHOE_CONTACTS');
write('amphoe_contacts.js', 'amphoeContacts', ac); // โหลดแบบ lazy เมื่อต้องใช้

// ---- ตรวจความสอดคล้องเบื้องต้น ----
const warn = [];
airports.forEach(a => { if (!/^VT[A-Z]{2}$/.test(a.icao)) warn.push('รหัส ICAO ผิดรูปแบบ: ' + a.icao + ' (' + a.nameTh + ')'); });
provinces.forEach(p => { if (!p.reg) warn.push('ไม่มีระเบียบจังหวัด: ' + p.th); });
const icaoSet = new Set(airports.map(a => a.icao));
provinces.forEach(p => {
  const t = p.reg && (p.reg.airportNotify || '');
  (t.match(/\bVT[A-Z]{2}\b/g) || []).forEach(code => {
    if (!icaoSet.has(code)) warn.push('ข้อความระเบียบ ' + p.th + ' อ้างรหัส ' + code + ' ซึ่งไม่มีในรายการสนามบิน');
    else {
      const ap = airports.find(a => a.icao === code);
      if (ap.provinceTh !== p.th) warn.push('ข้อความระเบียบ ' + p.th + ' อ้าง ' + code + ' แต่ในข้อมูลสนามบิน ' + code + ' = ' + ap.nameTh + ' จ.' + ap.provinceTh);
    }
  });
});
console.log('\nคำเตือนจากการตรวจข้อมูล (' + warn.length + '):');
warn.forEach(w => console.log(' - ' + w));
fs.writeFileSync(path.join(OUT, 'BUILD-WARNINGS.txt'), warn.join('\n') + '\n', 'utf8');
