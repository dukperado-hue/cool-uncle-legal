﻿/* ================================================================
   War Mode (constproc.html) — คลังข้อสอบเก่า วิ.ปกครอง / วิ.รัฐธรรมนูญ
   ข้อมูลอยู่ใน WAR_DATA (ด้านบนของไฟล์นี้) · ตัวแสดงผลอยู่ด้านล่าง
   ไม่มีชื่ออาจารย์/มหาวิทยาลัย และชื่อตัวละครในโจทย์ถูกเปลี่ยนแล้ว
   ================================================================ */
(function(){
  function esc(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;'); }
  function inl(s){ return esc(s).replace(/\*\*([\s\S]+?)\*\*/g,'<strong>$1</strong>'); }

  // ตัดชื่อสถาบัน/หน่วยภายในมหาวิทยาลัยออกจากบล็อกโจทย์ที่ยกมาจากคาบเรียน (ไม่แก้ต้นฉบับในหน้าบรรยาย)
  // WAR_SCRUB = [[regex-string, replacement], ...] (เก็บเป็น \\uXXXX ในไฟล์ข้อมูล)
  function scrub(html){
    return WAR_SCRUB.reduce(function(s, r){ return s.replace(new RegExp(r[0],'g'), r[1]); }, html);
  }

  function ansHtml(blocks){
    return blocks.map(b=>{
      const t=b[0], v=b[1];
      if(t==='h')  return '<div class="ans-issue">'+inl(v)+'</div>';
      if(t==='p')  return '<div>'+inl(v)+'</div>';
      if(t==='v')  return '<div><span class="verdict">'+inl(v)+'</span></div>';
      if(t==='ul') return '<ul class="war-ul">'+v.map(x=>'<li>'+inl(x)+'</li>').join('')+'</ul>';
      if(t==='off') return '<div class="war-off"><span class="war-off-tag">อนึ่ง (นอกประเด็นเล็กน้อย — แสดงความรู้ประกอบ)</span>'+inl(v)+'</div>';
      if(t==='note') return '<div class="war-note">'+inl(v)+'</div>';
      return '';
    }).join('');
  }

  function questionHtml(q){
    const facts=(q.facts||[]).map(p=>'<p>'+inl(p)+'</p>').join('');
    const asks=(q.asks||[]).map(p=>'<p class="war-ask">'+inl(p)+'</p>').join('');
    const kind=q.kind==='problem'?'โจทย์ตุ๊กตา':'โจทย์อธิบาย/แสดงความเห็น';
    const src=(q.src||[]).join(' · ');
    const ans=(q.answer&&q.answer.length)
      ? '<details class="war-ans"><summary>👁 ดูธงคำตอบ</summary><div class="exam-answer"><div class="ans-title">'+(q.answerTitle||'ธงคำตอบ (ร่าง — ตรวจซ้ำกับตัวบทและเอกสารประกอบก่อนใช้จริง)')+'</div>'+ansHtml(q.answer)+'</div></details>'
      : '<div class="war-note">⏳ ธงคำตอบข้อนี้รอเพิ่มหลังอาจารย์บรรยาย</div>';
    return '<div class="war-q" id="wq-'+q.id+'">'
      + '<div class="war-q-head"><span class="war-q-id">'+q.id+'</span><span class="war-q-kind">'+kind+'</span></div>'
      + '<div class="war-q-title">'+inl(q.title)+'</div>'
      + '<div class="war-q-src">ออกสอบ: '+esc(src)+'</div>'
      + '<div class="war-q-body">'+facts+asks+'</div>'
      + ans + '</div>';
  }

  function panelHtml(part){
    const D=WAR_DATA, P=D.parts[part];
    const issues=D.issues.filter(i=>i.part===part);
    const qs=D.questions.filter(q=>q.part===part);
    let h='<div class="board-note war-intro"><div class="board-note-title">'+esc(P.title)+'</div>'+P.intro.map(x=>'<p>'+inl(x)+'</p>').join('')+'</div>';
    h+='<div class="war-map"><div class="war-map-title">แผนที่ประเด็น (กดเพื่อกระโดดไป)</div>'
      + issues.map(i=>'<a class="war-chip" href="#war-issue-'+i.n+'" onclick="warJump(event,'+i.n+')"><b>'+i.n+'</b> '+esc(i.short)+'<span class="war-chip-n">'+i.count+' โจทย์</span></a>').join('')+'</div>';
    issues.forEach(i=>{
      const iq=qs.filter(q=>q.issue===i.n);
      h+='<details class="war-issue" id="war-issue-'+i.n+'" open><summary><span class="war-issue-n">'+i.n+'</span><span class="war-issue-name">'+esc(i.name)+'</span><span class="war-issue-freq">'+esc(i.freq)+'</span></summary>'
        + '<div class="war-issue-body"><div class="war-keys"><div class="war-keys-title">หลักที่ต้องมี (ธงประเด็น)</div>'+i.keys.map(k=>'<div>'+inl(k)+'</div>').join('')+'</div>'
        + iq.map(questionHtml).join('') + '</div></details>';
    });
    if(part==='A') h+=lectureBankHtml();
    return h;
  }

  function lectureBankHtml(){
    if(typeof LECTURES==='undefined') return '';
    const defs=[[5,'§§EXAM§§','คาบที่ 5 — ผู้มีสิทธิฟ้อง (10 ข้อ)'],[6,'§§EXAM6§§','คาบที่ 6 — คำบังคับมาตรา 72 และการอุทธรณ์ก่อนฟ้อง (3 ข้อ)'],[7,'§§EXAM7§§','คาบที่ 7 — เฉลยข้อ 4–7 ของคาบที่ 6 (4 ข้อ)'],[8,'§§EXAM8§§','คาบที่ 8 — อายุความ ข้อห้ามฟ้อง และวิธีการชั่วคราว (10 ข้อ)']];
    let inner='';
    defs.forEach(d=>{
      const l=LECTURES.find(x=>x.n===d[0]);
      const html=l&&l.inlineMedia&&l.inlineMedia[d[1]];
      if(!html) return;
      inner+='<details class="war-lec"><summary>'+esc(d[2])+'</summary><div class="war-lec-body">'+scrub(html)+'<div class="war-note">อ่านเนื้อหาบรรยายที่เกี่ยวข้อง: <a href="#" onclick="warOpenLecture('+d[0]+');return false;">เปิดบรรยายครั้งที่ '+d[0]+'</a></div></div></details>';
    });
    if(!inner) return '';
    return '<details class="war-issue" id="war-issue-lec" open><summary><span class="war-issue-n">★</span><span class="war-issue-name">โจทย์ที่อาจารย์เฉลยในคาบ (ครั้งที่ 5–8) — 27 ข้อ</span><span class="war-issue-freq">เฉลยตามที่บรรยายจริง</span></summary>'
      + '<div class="war-issue-body"><div class="war-keys"><div class="war-keys-title">วิธีใช้</div><div>ชุดนี้คือโจทย์ตุ๊กตาที่อาจารย์เฉลยเองในคาบ ใช้เป็นต้นแบบการเขียนตอบ (เขตอำนาจมาตรา 9 → ผู้มีสิทธิฟ้องมาตรา 42 → อุทธรณ์ก่อนฟ้อง → ระยะเวลา → ค่าธรรมเนียม) หลายข้อซ้ำหรือใกล้เคียงกับโจทย์ในข้อสอบเก่าด้านบน</div></div>'+inner+'</div></details>';
  }

  window.warJump=function(ev,n){
    ev.preventDefault();
    const el=document.getElementById('war-issue-'+n);
    if(el){ el.open=true; el.scrollIntoView({behavior:'smooth',block:'start'}); }
  };
  window.warOpenLecture=function(n){
    switchMode('read');
    setTimeout(function(){ const r=document.getElementById('lec-'+n); if(r){ if(!r.classList.contains('open')) toggleLecture(n); r.scrollIntoView({behavior:'smooth',block:'start'}); } },50);
  };

  window.renderWarPanels=function(){
    const a=document.getElementById('panel-waradmin'), c=document.getElementById('panel-warconst');
    if(a) a.innerHTML=panelHtml('A');
    if(c) c.innerHTML=panelHtml('C');
  };
})();


