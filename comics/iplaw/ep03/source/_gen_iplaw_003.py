def ch(who, expr=None, x=50, h=100, top=4, shot="half", **k):
    d = {"who": who, "x": x, "y": 100, "h": h, "top": top, "shot": shot}
    if expr:
        d["expr"] = expr
        d.pop("shot")
    d.update(k)
    return d


def sp(text, size=22, name=None, t="speech", **k):
    b = {"t": t, "text": text, "size": size}
    if name:
        b["name"] = name
    b.update(k)
    return b


def pn(bg, chars, bubbles, w=1, cap=None, **k):
    d = {"band": "auto", "bg": bg, "chars": chars, "bubbles": bubbles, "w": w}
    if cap:
        d["caption"] = cap
    d.update(k)
    return d


def G(a, b, deg=160): return {"style": "gradient", "c1": a, "c2": b, "deg": deg}
def CHK(a, b): return {"style": "checker", "c1": a, "c2": b}
def GRID(a): return {"style": "grid", "c1": a}
def FLAT(a): return {"style": "flat", "c1": a}
def HALF(a, b): return {"style": "halftone", "c1": a, "c2": b}


def BOX(text, name="สรุป", size=25):
    return {"bg": FLAT("#fff8e2"), "bubbles": [{"t": "box", "name": name, "size": size, "text": text, "x": 3, "y": 8, "w": 94}]}


def t(who, expr, text, bg, cap, w=1, size=21, **k):
    return pn(bg, [ch(who, expr, x=50, h=100)], [sp(text, size)], w=w, cap=cap, **k)


